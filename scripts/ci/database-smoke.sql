-- Owner A must see only its own tenant and must not insert into tenant B.
begin;
set local role authenticated;
select set_config('request.jwt.claim.sub', '10000000-0000-4000-8000-000000000001', true);
select set_config('test.company_b_id', :'company_b_id', true);
do $$
declare
  own_count integer;
  foreign_count integer;
begin
  select count(*) into own_count from public.customers;
  if own_count <> 1 then
    raise exception 'Tenant isolation failed: owner A expected 1 customer, got %', own_count;
  end if;

  select count(*) into foreign_count from public.customers where name = 'Cliente B';
  if foreign_count <> 0 then
    raise exception 'Tenant isolation failed: owner A can read customer B';
  end if;

  begin
    insert into public.customers (company_id, name)
    values (current_setting('test.company_b_id')::uuid, 'Tentativa indevida');
    raise exception 'Tenant isolation failed: cross-company insert unexpectedly succeeded';
  exception
    when insufficient_privilege then null;
  end;
end;
$$;
rollback;

-- Quote totals and audit events must be generated by the database.
begin;
set local role authenticated;
select set_config('request.jwt.claim.sub', '10000000-0000-4000-8000-000000000001', true);
select set_config('test.quote_a_id', :'quote_a_id', true);
do $quote$
declare
  actual_subtotal numeric(12,2);
  actual_total numeric(12,2);
  audit_count integer;
begin
  select subtotal, total_amount into actual_subtotal, actual_total
  from public.quotes
  where id = current_setting('test.quote_a_id')::uuid;

  if actual_subtotal <> 250.00 or actual_total <> 240.00 then
    raise exception 'Quote totals incorrect: subtotal %, total %', actual_subtotal, actual_total;
  end if;

  select count(*) into audit_count
  from public.audit_logs
  where entity_table = 'customers' and action = 'INSERT';

  if audit_count <> 1 then
    raise exception 'Expected one customer audit event, got %', audit_count;
  end if;
end; 
$quote$;
rollback;

